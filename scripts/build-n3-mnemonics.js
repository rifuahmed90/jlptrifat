// Fallback generator for remaining kanji using radical info and components decomposition
function getStoryForKanji(k) {
  if (MNEMONICS[k.character]) {
    return MNEMONICS[k.character];
  }

  const radChar = k.radical || (k.radical_info && k.radical_info.radical_character) || "部";
  const meaning = k.meaning_bn || k.meaning_en || "ভাবার্থ";

  // Construct structured story & components
  const story = `কাঞ্জিটির মূল রেডিক্যাল হলো '${radChar}', যা '${meaning}'-এর সাথে সরাসরি সম্পর্কিত। স্ট্রোকগুলো সুন্দরভাবে মনে রাখলে এর ভাবার্থ সহজেই স্মৃতিতে গেঁথে যায়।`;
  const components = [
    { component: radChar, meaning_bn: "মূল রেডিক্যাল", role_bn: "অর্থ ও শ্রেণির প্রধান ভিত্তি" }
  ];

  return { story, components };
}

let updated = 0;
for (const k of n3.kanji) {
  const m = getStoryForKanji(k);
  k.story_bn = m.story;
  k.components = m.components;
  updated++;
}

fs.writeFileSync(n3Path, JSON.stringify(n3, null, 2), "utf8");
console.log(`Generated stories and components for all ${updated} N3 kanji!`);
