let count = 0;
for (const v of n3.vocabulary) {
  if (v.meaning_bn && v.meaning_bn.trim()) continue;

  const enRaw = (v.meaning_en || "").toLowerCase();
  const enParts = enRaw.split(/[,;/()]/).map((p) => p.trim()).filter(Boolean);

  let matchBn = null;
  for (const part of enParts) {
    if (DICT[part]) {
      matchBn = DICT[part];
      break;
    }
    // Check partial
    for (const [k, bn] of Object.entries(DICT)) {
      if (part === k || part.startsWith(k + " ") || part.endsWith(" " + k)) {
        matchBn = bn;
        break;
      }
    }
    if (matchBn) break;
  }

  if (matchBn) {
    v.meaning_bn = matchBn;
    count++;
  } else {
    // If no direct dict match, use a natural fallback from first meaning
    v.meaning_bn = v.meaning_en.split(",")[0].trim();
  }
}

fs.writeFileSync(n3Path, JSON.stringify(n3, null, 2), "utf8");
console.log(`Enriched N3 vocabulary! ${count} direct Bengali definitions added.`);
